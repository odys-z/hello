#!/usr/bin/env python3
"""Write sphinx/manifest.json (the Sphinx source files the playground loads into Pyodide),
then serve the playground and print its URL.

    python3 start_with_manifest.py         # manifest + server on http://localhost:8997/
    python3 start_with_manifest.py --port 8000
    python3 start_with_manifest.py --no-serve # manifest only

Run it again after the source changes (a page added, renamed or removed).

Layout it expects (both are symlinks into the odys-z.github.io checkout next to hello/):

    hello/rst-playground/sphinx/source  -> ../../../odys-z.github.io/sphinx/products/portfolio/source
    hello/rst-playground/sphinx/_static -> ../../../odys-z.github.io/products/portfolio/_static
    hello/rst-playground/sphinx/_images -> ../../../odys-z.github.io/products/portfolio/_images

script.js fetches each listed file from sphinx/source/ and writes it to the same path
under /sphinx/source/ in Pyodide. Only the English build is listed: the language folders
(zh-CN, zh-TW, ...) are separate builds, found by the same rule as the Makefile.
"""
import argparse
import http.server
import json
import os
import re
import sys
from pathlib import Path

# Paths are relative to this script's folder (hello/rst-playground/), wherever it is run from.
HERE = Path(__file__).resolve().parent
SOURCE = Path("sphinx/source")
OUTPUT = Path("sphinx/manifest.json")

# File types Sphinx reads for the English HTML build.
INCLUDE = {".rst", ".py", ".css", ".png", ".jpg", ".jpeg", ".gif", ".svg"}
# Larger files are left out (the setup video, 5 MB): Sphinx warns, the page still builds.
MAX_BYTES = 1_000_000
# Same pattern as the Makefile's LANGS: zh-CN, zh-TW, ja, pt-BR ...
LANGUAGE_FOLDER = re.compile(r"^[a-z]{2,3}(-[A-Za-z0-9]{2,4})?$")
SKIP_FOLDERS = {"__pycache__", "_build", "_templates"}


def main() -> None:
    parser = argparse.ArgumentParser(description="Write sphinx/manifest.json and serve the playground.")
    parser.add_argument("--port", type=int, default=8997, help="HTTP port (default 8997)")
    parser.add_argument("--no-serve", action="store_true", help="only write the manifest")
    args = parser.parse_args()

    os.chdir(HERE)
    write_manifest()
    if not args.no_serve:
        serve(args.port)


def write_manifest() -> None:
    if not SOURCE.is_dir():
        sys.exit(f"{SOURCE} not found. Create the symlinks first (see README.md).")

    files, skipped = [], []
    for root, dirs, names in os.walk(SOURCE, followlinks=True):
        rel_root = Path(root).relative_to(SOURCE)
        top_level = rel_root == Path(".")
        dirs[:] = sorted(
            d for d in dirs
            if not d.startswith(".") and d not in SKIP_FOLDERS
            and not (top_level and LANGUAGE_FOLDER.match(d))
        )
        for name in sorted(names):
            path = Path(root) / name
            rel = (rel_root / name).as_posix()
            if path.suffix.lower() not in INCLUDE:
                skipped.append(f"{rel} (type)")
            elif path.stat().st_size > MAX_BYTES:
                skipped.append(f"{rel} ({path.stat().st_size // 1024} KB)")
            else:
                files.append(rel)

    total = sum((SOURCE / f).stat().st_size for f in files)
    manifest = {
        "comment": "Generated by start_with_manifest.py; paths are relative to sphinx/source/.",
        "source": "sphinx/source/",
        "files": files,
    }
    OUTPUT.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"{OUTPUT}: {len(files)} files, {total // 1024} KB")
    for s in skipped:
        print(f"  skipped {s}")


class NoCacheHandler(http.server.SimpleHTTPRequestHandler):
    """Static files with "Cache-Control: no-cache": the browser asks again on every load
    (a cheap 304 when unchanged), so edits to the .rst files show up after a page reload."""

    def end_headers(self):
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()


def serve(port: int) -> None:
    """Like `python3 -m http.server PORT` in this folder: fetch() and the blob
    preview need http://, not file://."""
    try:
        server = http.server.ThreadingHTTPServer(("", port), NoCacheHandler)
    except OSError as e:
        sys.exit(f"Cannot listen on port {port}: {e.strerror}. Try --port <other>.")
    print(f"\nPreview: http://localhost:{port}/index.xhtml   (Ctrl+C to stop)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
